-- 2026-09-16 一堂課可以開好幾張課表
-- 使用者：「我要在課卡點課表以後 出現課表頁面 這個頁面可以好幾張
--          就像一堂課教練會拿兩份課表分別記錄不同的訓練
--          每次由教練決定要開一份還是兩份課表出來寫」
--
-- 語意：sheet = 這筆紀錄寫在第幾張課表上（教練手上的紙）。
--   sheet = null 或 1 → 第一張（所有舊資料都是這個，不必回填）
--   sheet = 2, 3, …   → 教練自己按 [+] 開出來的第二張、第三張
--
-- ⚠⚠ 這一欄與 slot 是**兩個互不相干的維度**，不可以混用：
--   ・slot  = 「這筆不是這位會員的」（1V2 的第二位學員，借掛在第一位的 member_id 上）
--             → 所有「以會員身分看自己」的讀取端都必須濾掉 slot=2，全站八處，
--               漏一處就會出現「別人的 PR 算到我頭上」（見 20260915_training_logs_slot.sql）
--   ・sheet = 「同一位會員、同一堂課，教練把訓練分成幾張紙記」
--             → **每一張都是這位會員的紀錄**，全部都要算進他的歷史與三大項 PR，
--               任何讀取端都不可以因為 sheet>=2 就把它濾掉。
--   一堂 1V2 的課如果教練又開了兩張課表，兩個維度會交叉（slot 1/2 × sheet 1/2），
--   彼此獨立，不會互相影響。
--
-- ⚠ 不加 NOT NULL、不設 default：舊資料維持 null，讀取端一律用「null 或 1 都當第一張」判斷，
--   這樣不必回填四千多筆，也不會因為回填失敗留下半套狀態。
-- ⚠ 不做 unique 或 check：張數由前端決定（教練想開幾張就幾張），資料庫不設上限；
--   前端會擋在合理範圍內，避免誤觸開出幾十張。
-- ⚠ RLS 不動：授權依據仍是 member_id／coach_id，這一欄只是分頁用的標記。
-- ⚠ trg_change_log 已經在這張表上，加欄位不需要重建觸發器
--   （新表才需要一併加觸發器並列進 fn_table_sigs，這裡是既有表）。
alter table public.training_logs
  add column if not exists sheet smallint;

comment on column public.training_logs.sheet is
  '這筆寫在第幾張課表上：null/1=第一張（舊資料皆此），2 以上=教練另外開的課表。與 slot 無關——每一張都屬於同一位會員，讀取端不可因 sheet>=2 而濾除。';
