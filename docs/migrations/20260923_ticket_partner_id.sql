-- ══ 1V2 的同行會員（2026-09-23）══════════════════════════════════════════
-- 使用者 0922 提案：「如果是1V2的方案 可以新增另一位會員進來…重點是課表本來是
-- [會員A][會員B] 現在這樣可以帶入兩個會員的名字 教練紀錄的時候可以知道這張課表是給誰的」
--
-- 背景（0921/0922 查證，別再重查）：1V2 在資料層是**一張 booking、綁一位會員**，
-- 610 堂裡 452 堂只有單張，bookings.member_ids 一筆都沒填 —— 第二位根本不存在資料裡，
-- 所以課表只能標「會員 A／會員 B」。這個欄位就是把第二位存下來。
--
-- ⚠⚠ 這不是 shared_with（票券共享）。使用者明講「跟共享這個按鈕的定義不一樣」：
--   ・shared_with：共用同一個堂數池，**對方可以拿這張票去約課、會扣堂數**
--   ・partner_id ：只是「這堂課還有這一位一起上」，**不扣他的課、他也不能約課**
--   使用者確認過收費現況：「只有一位付錢、另一位跟著上」。
--
-- ⚠ 存在票上不是存在每一堂課上：一次設定、那張票的所有課都適用，610 堂不用回填。
-- ⚠ 談定的範圍只有兩件：① 課表顯示兩個真名 ② 第二位看得到這張票的課程預約。
--   合約簽名**不做**（使用者：「我們在紙本簽約的時候只留下其中一個會員的姓名做代表
--   只有他簽名」）；自主訓練**不送**（那是另一張票的權益）。
alter table member_tickets
  add column if not exists partner_id text;

comment on column member_tickets.partner_id is
  '1V2 同行的第二位會員（members.id）。只是一起上課：不扣他的課、他不能拿這張票約課。'
  '⚠ 與 shared_with 不同——那個是共用堂數池、對方可以約課。';

-- 查詢用：會員端要問「有哪些票把我設成同行」
create index if not exists idx_member_tickets_partner on member_tickets(partner_id)
  where partner_id is not null;
