-- 2026-09-17 待補發票資料：可以逐筆「不再提醒」
-- 使用者：「首頁的 待補發票通知可以關閉 有些客人應該不會再出現
--          這樣這個通知會一直存在」
-- 使用者定案兩件事：
--   ① 記在會員資料上（不是 localStorage）—— 櫃檯、教練、換電腦都看得到同一份
--   ② 「下次來上課就重新提醒」
--
-- ⚠ 所以這一欄存的是**日期**而不是布林值：
--   布林值只能表達「關掉了」，沒辦法回答「關掉之後他有沒有再來」。
--   存下按鈕按下去的那一天，判斷就變成「這位近 90 天內的最後上課日 > 這個日期嗎」。
--   ・沒來過     → 不提醒（櫃檯已經處理過了）
--   ・又來上課了 → 自動重新出現在名單上，不必櫃檯手動取消
--
-- ⚠ 用 date 不用 timestamptz：比較的對象是 bookings.date（純日期）。
--   混用時間戳會在「同一天忽略又同一天上課」的邊界出現說不清楚的行為；
--   用日期則語意明確 —— 忽略當天的課不算重新提醒（櫃檯今天就是問過了才按的），
--   隔天以後的課才會讓它回到名單。
--
-- ⚠⚠ **不要**把這一欄加進 fn_members_guard 的白名單（20260805 那支）：
--   那份白名單的意思是「會員自己可以改的欄位」，而這個旗標是**櫃檯的判斷**。
--   加進去等於讓會員可以自己把催補發票的提醒關掉。
--   櫃檯本來就寫得進來 —— guard 裡第一件事就是 `if is_staff_desk() then return new;`，
--   RLS 的 members_update 也允許 is_staff_desk()。實測前已確認這兩條。
--
-- ⚠ 不設 default、允許 null：null＝從來沒被收起來過，也就是舊資料的預設狀態，
--   不必回填任何一筆。
-- ⚠ RLS 不動；trg_change_log 已在 members 上，加欄位不必重建觸發器
--   （新表才需要一併加觸發器並列進 fn_table_sigs）。
alter table public.members
  add column if not exists invoice_skip_date date;

comment on column public.members.invoice_skip_date is
  '櫃檯在「待補發票資料」名單上按「不再提醒」的日期。null=沒收起來過。判斷方式：這位近 90 天內的最後上課日 > 這個日期，就重新回到名單（下次來上課就重新提醒）。不屬於 fn_members_guard 的會員自助白名單——這是櫃檯的判斷，會員不可自行關閉。';
